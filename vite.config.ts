import { createHash } from 'node:crypto';
import { readdirSync } from 'node:fs';
import { loadEnv, type Plugin } from 'vite';
import { configDefaults, defineConfig } from 'vitest/config';

/**
 * Emits sw.js after bundling with the exact list of built files, so the whole
 * game is cached on first visit and then runs with no network (NFR-02).
 * The cache name is a hash of that list, so each release replaces the old cache.
 */
const offlineServiceWorker = (): Plugin => ({
  name: 'offline-service-worker',
  apply: 'build',
  generateBundle(_options, bundle) {
    const publicFiles = readdirSync('public');
    const files = ['./', ...publicFiles, ...Object.keys(bundle)].map((f) => (f.startsWith('./') ? f : `./${f}`));
    const version = createHash('sha256').update(files.join('\n')).digest('hex').slice(0, 12);
    this.emitFile({
      type: 'asset',
      fileName: 'sw.js',
      source: `// Generated by vite.config.ts
const CACHE = 'fuse-and-fall-${version}';
const FILES = ${JSON.stringify(files)};

self.addEventListener('install', (event) => {
  event.waitUntil(caches.open(CACHE).then((cache) => cache.addAll(FILES)).then(() => self.skipWaiting()));
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches.keys()
      .then((keys) => Promise.all(keys.filter((k) => k !== CACHE).map((k) => caches.delete(k))))
      .then(() => self.clients.claim()),
  );
});

self.addEventListener('fetch', (event) => {
  if (event.request.method !== 'GET') return;
  event.respondWith(
    caches.match(event.request, { ignoreSearch: true }).then((hit) => {
      if (hit) return hit;
      if (event.request.mode === 'navigate') return caches.match('./');
      return fetch(event.request);
    }),
  );
});
`,
    });
  },
});

/**
 * Store builds must follow the real progression: a release build with the
 * test switch on fails here. Every build records what it is in
 * build-info.json, which the Android release build checks in turn.
 */
const buildInfo = (mode: string): Plugin => {
  const env = loadEnv(mode, process.cwd(), 'VITE_');
  const unlockAll = env.VITE_UNLOCK_ALL === '1';
  return {
    name: 'build-info',
    apply: 'build',
    buildStart() {
      if (mode === 'release' && unlockAll) this.error('VITE_UNLOCK_ALL=1 in a release build: every city would ship unlocked. Remove it from .env.release.');
    },
    generateBundle() {
      this.emitFile({
        type: 'asset',
        fileName: 'build-info.json',
        source: JSON.stringify({ mode, unlockAll, realAds: Boolean(env.VITE_ADMOB_REWARDED_ID) }),
      });
    },
  };
};

export default defineConfig(({ mode }) => ({
  base: './',
  build: { target: 'es2022' },
  plugins: [buildInfo(mode), offlineServiceWorker()],
  test: {
    environment: 'node',
    // `.claude` holds agent worktrees: other checkouts of this repo, tested from their own folders.
    exclude: [...configDefaults.exclude, '.claude/**'],
    coverage: {
      include: ['src/core/**', 'src/infrastructure/**', 'src/app/offer-desk.ts', 'src/app/attempt.ts', 'src/app/progression.ts', 'src/app/screen-flow.ts'],
      // NFR-09: game rules stay at or above 80% coverage.
      thresholds: { lines: 80, statements: 80, functions: 80, branches: 75 },
    },
  },
}));
